/// Computes rook attacks using magic bitboards in O(1).
#[must_use]
pub const fn rook_attacks(sq: Square, occupied: Bitboard) -> Bitboard {
    let idx = sq.index();
    let occ = (occupied.as_raw() & ROOK_MASKS[idx]).wrapping_mul(ROOK_MAGICS[idx]);
    let offset = (occ >> ROOK_SHIFTS[idx]) as usize;
    ROOK_ATTACK_TABLE[idx][offset]
}

/// Computes bishop attacks using magic bitboards in O(1).
#[must_use]
pub const fn bishop_attacks(sq: Square, occupied: Bitboard) -> Bitboard {
    let idx = sq.index();
    let occ = (occupied.as_raw() & BISHOP_MASKS[idx]).wrapping_mul(BISHOP_MAGICS[idx]);
    let offset = (occ >> BISHOP_SHIFTS[idx]) as usize;
    BISHOP_ATTACK_TABLE[idx][offset]
}

/// Computes queen attacks using magic bitboards in O(1).
#[must_use]
pub fn queen_attacks(sq: Square, occupied: Bitboard) -> Bitboard {
    rook_attacks(sq, occupied) | bishop_attacks(sq, occupied)
}
